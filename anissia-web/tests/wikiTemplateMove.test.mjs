import assert from 'node:assert/strict';
import {test} from 'node:test';
import {createNabiWith, wings} from 'nabi-note';
import {moveWikiTemplate} from '../src/domain/wiki/wikiTemplateMove.ts';

const template = id => ({w: 'p', _id: id, ch: [{w: 'exTemplateInclude', a: {exTemplateNo: '17'}, ch: []}]});
const paragraph = (id, text = id) => ({w: 'p', _id: id, ch: [text]});
const selection = {anchor: {path: [0], offset: 0}, focus: {path: [0], offset: 1}};
const env = {blockHolders: new Set(['quote', 'details', 'td', 'float'])};
test('moves a template across paragraphs without expanding it or mutating the document', () => {
  const doc = [template('t'), paragraph('a'), paragraph('b')], snapshot = structuredClone(doc);
  const result = moveWikiTemplate(doc, selection, {sourceKey: 't', targetKey: 'b', after: true}, env);
  assert.deepEqual(result.doc.map(node => node._id), ['a', 'b', 't']);
  assert.equal(result.doc[2], doc[0]);
  assert.deepEqual(doc, snapshot);
  assert.deepEqual(result.selection.focus.path, [2]);
  assert.equal(moveWikiTemplate(doc, selection, {sourceKey: 't', targetKey: 'a', after: false}, env), null);
  assert.equal(moveWikiTemplate(doc, selection, {sourceKey: 't', targetKey: 't', after: true}, env), null);
  assert.equal(moveWikiTemplate(doc, selection, {sourceKey: 'a', targetKey: 'b'}, env), null);
});
test('moving out of the last nested slot leaves a valid empty paragraph', () => {
  const doc = [{w: 'p', ch: [{w: 'quote', ch: [template('t')]}]}, paragraph('a')];
  const result = moveWikiTemplate(doc, selection, {sourceKey: 't', targetKey: 'a', after: true}, env);
  assert.deepEqual(result.doc[0].ch[0].ch, [{w: 'p', ch: []}]);
  assert.equal(result.doc[2].ch[0].a.exTemplateNo, '17');
});
test('Nabi records template movement as one undoable edit', () => {
  const {nabi} = createNabiWith([...wings().allBasic().build(), {
    w: 'exTemplateInclude', place: 'void', attrs: ['exTemplateNo'], commands: {moveWikiTemplate},
    toHtml: (_node, _children, context) => context.element('section', '템플릿'),
  }]);
  nabi.setJson([template('t'), paragraph('a'), paragraph('b')]);
  // Imported keys are regenerated by Nabi; public editor HTML exposes the current keys.
  const keys = [...nabi.getEditorHtml().matchAll(/<(?:p|div) data-key="([^"]+)"/g)].map(match => match[1]);
  const before = nabi.getJson();
  assert.equal(keys.length, 3);
  assert.equal(nabi.applyCommand('moveWikiTemplate', {sourceKey: keys[0], targetKey: keys[2], after: true}), true);
  assert.equal(nabi.getJson()[2].ch[0].w, 'exTemplateInclude');
  assert.equal(nabi.undo(), true);
  assert.deepEqual(nabi.getJson(), before);
  assert.equal(nabi.redo(), true);
  assert.equal(nabi.getJson()[2].ch[0].a.exTemplateNo, '17');
});
